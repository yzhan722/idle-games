/* ---------------- apply ---------------- */

function apply(file, maps){
	var json = JSON.parse(fs.readFileSync(file, "utf8"));
	var touched = 0, created = [];
	maps.forEach(function(map){
		for (var k in map){
			if (!(k in json)) { created.push(k); }
			if (json[k] !== map[k]) { json[k] = map[k]; touched++; }
		}
	});
	fs.writeFileSync(file, JSON.stringify(json, null, "\t") + "\n", "utf8");
	console.log(path.basename(file) + ": " + touched + " keys applied, " + created.length + " new keys");
	if (created.length){ console.log("  new: " + created.join(", ")); }
}

