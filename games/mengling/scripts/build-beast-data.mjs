// build-beast-data.mjs — 生成 data/beasts.js：全部物种数据。
// 输入：data/beast_traits.json（编号 / 属性 / 生态区 / 家族关系）、data/beasts_zh.js（名表与图鉴志）、
//       scripts/beast_rules.mjs（自有数值规则）。不读 scripts/_srcdata。
// 输出：data/beasts.js
// 用法：node scripts/build-beast-data.mjs [--check]（--check 只比对，不写文件）

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { buildOwnNumbers, pidOf } from "./beast_rules.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
(0, eval)(readFileSync(join(root, "data", "beasts_zh.js"), "utf8"));
const traits = JSON.parse(readFileSync(join(root, "data", "beast_traits.json"), "utf8"));
const roster = traits.map((t) => t.dex);
const own = buildOwnNumbers(traits);

const zh = {};
const titleMap = {};
const descMap = {};
const orderMap = {};
for (const t of traits) {
  const id = pidOf(t.dex);
  zh[id] = globalThis.BEAST_ZH[id];
  if (!zh[id]) throw new Error(`missing beast name for ${id}`);
  if (globalThis.BEAST_ORDER?.[id] !== t.n) throw new Error(`catalog number mismatch for ${id}`);
  titleMap[id] = globalThis.BEAST_TITLE?.[id] || "星野幻灵";
  descMap[id] = globalThis.BEAST_DESC?.[id] || "栖息于星野秘境的奇异生灵。";
  orderMap[id] = t.n;
}

const out = `// beasts.js — GENERATED by scripts/build-beast-data.mjs；勿手改。
// 萌灵数据（${roster.length} 种）：名表与图鉴志手写于 data/beasts_zh.js，数值由 scripts/beast_rules.mjs 的自有规则生成。
globalThis.BEAST_ROSTER=${JSON.stringify(roster)};
globalThis.BEAST_ZH=${JSON.stringify(zh)};
globalThis.BEAST_TITLE=${JSON.stringify(titleMap)};
globalThis.BEAST_DESC=${JSON.stringify(descMap)};
globalThis.BEAST_ORDER=${JSON.stringify(orderMap)};
globalThis.BEAST_TYPES=${JSON.stringify(own.types)};
globalThis.BEAST_EVO=${JSON.stringify(own.evo)};
globalThis.BEAST_EVO_REQ=${JSON.stringify(own.evoReq)};
globalThis.BEAST_TIER=${JSON.stringify(own.tier)};
globalThis.BEAST_TAME=${JSON.stringify(own.tame)};
globalThis.BEAST_STATS=${JSON.stringify(own.stats)};
globalThis.BEAST_ZONES=${JSON.stringify(own.zones)};
`;
const outPath = join(root, "data", "beasts.js");
if (process.argv.includes("--check")) {
  const same = readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") === out;
  console.log(same ? "data/beasts.js matches the rules" : "data/beasts.js is stale: run node scripts/build-beast-data.mjs");
  process.exit(same ? 0 : 1);
}
writeFileSync(outPath, out);

// 自动同步 modules/pve_defs.js 中的敌人名称以匹配最新 BEAST_ZH
const pvePath = join(root, "modules", "pve_defs.js");
const pveRaw = readFileSync(pvePath, "utf8");
const pveSynced = pveRaw.replace(/\{\s*dex:\s*(\d+)\s*,\s*name:\s*"[^"]*"/g, (m, dStr) => {
  const newName = zh[pidOf(Number(dStr))];
  return newName ? `{ dex: ${dStr}, name: "${newName}"` : m;
});
if (pveSynced !== pveRaw) {
  writeFileSync(pvePath, pveSynced);
  console.log("synced enemy names in modules/pve_defs.js");
}

const count = (list) => list.reduce((m, x) => ({ ...m, [x]: (m[x] ?? 0) + 1 }), {});
console.log(`wrote data/beasts.js — ${roster.length} species, ${Object.values(own.evo).flat().length} evolution links`);
console.log("rarity:", JSON.stringify(count(Object.values(own.tier))));
console.log("zones:", JSON.stringify(count(Object.values(own.zones))));
console.log("types9:", JSON.stringify(count(Object.values(own.types).flat())));
