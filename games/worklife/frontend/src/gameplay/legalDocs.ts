export const LEGAL_DOCS: Record<LegalDocId, LegalDoc> = { privacy: PRIVACY_POLICY, terms: TERMS_OF_SERVICE };

/** 地址栏 #privacy / #terms 对应的文档。 */
export function legalDocFromHash(hash: string): LegalDoc | null {
  const id = hash.replace(/^#\/?/, "");
  return id === "privacy" || id === "terms" ? LEGAL_DOCS[id] : null;
}

/** 这一版条款是否已经勾选过。 */
export function legalAccepted(stored: string | null | undefined): boolean {
  return stored === LEGAL_VERSION;
}
