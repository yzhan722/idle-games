import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { T1_ASSET_CONTRACT, T1_EXTENSION_PRIORITY, type T1Extension } from "../frontend/src/assets/t1/contract";
import { rasterSize } from "./art-image-meta";

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const t1Root = path.join(repoRoot, "frontend", "src", "assets", "t1");
const statusPath = path.join(repoRoot, "docs", "art", "T1_ASSET_STATUS.md");
const WARN_BYTES = 5 * 1024 * 1024;

type Found = { ext: T1Extension; abs: string; bytes: number };

function walkFiles(dir: string, acc: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const abs = path.join(dir, name);
    if (statSync(abs).isDirectory()) walkFiles(abs, acc);
    else acc.push(abs);
  }
  return acc;
}

function findForKey(key: string): Found[] {
  const found: Found[] = [];
  for (const ext of T1_EXTENSION_PRIORITY) {
    const abs = path.join(t1Root, `${key}.${ext}`);
    if (existsSync(abs)) found.push({ ext, abs, bytes: statSync(abs).size });
  }
  return found;
}

function liveLane(key: string, specStatus: string, found: Found[]): "PRODUCTION" | "PLACEHOLDER" | "MISSING" {
  const raster = found.find((f) => f.ext === "webp" || f.ext === "png");
  if (raster && raster.bytes > 0) return "PRODUCTION";
  if (found.some((f) => f.ext === "svg" && f.bytes > 0)) return "PLACEHOLDER";
  if (specStatus === "MISSING" && found.length === 0) return "MISSING";
  return found.length ? "PLACEHOLDER" : "MISSING";
}

const warnings: string[] = [];
const errors: string[] = [];
const lines: string[] = [
  "# T1 Asset Status",
  "",
  "Generated by `npm run verify:art`. Do not hand-edit the P0/P1 lanes.",
  "Visual acceptance is appended from `T1_ASSET_VISUAL_ACCEPTANCE.md`.",
  "",
];

const byPriority = { P0: T1_ASSET_CONTRACT.filter((s) => s.priority === "P0"), P1: T1_ASSET_CONTRACT.filter((s) => s.priority === "P1"), P2: T1_ASSET_CONTRACT.filter((s) => s.priority === "P2") };

for (const band of ["P0", "P1", "P2"] as const) {
  const specs = byPriority[band];
  if (!specs.length) continue;
  const counts = { REQUIRED: specs.length, PRODUCTION: 0, PLACEHOLDER: 0, MISSING: 0 };
  lines.push(`## ${band}`, "");
  for (const spec of specs) {
    const found = findForKey(spec.key);
    for (const f of found) {
      if (f.bytes === 0) errors.push(`0-byte ${spec.key}.${f.ext}`);
      if (f.bytes > WARN_BYTES) warnings.push(`${spec.key}.${f.ext} is ${(f.bytes / 1024 / 1024).toFixed(1)} MB`);
      if (f.ext === "png" || f.ext === "webp") {
        const size = rasterSize(readFileSync(f.abs), f.ext);
        if (!size) errors.push(`unreadable ${spec.key}.${f.ext}`);
        else if (Math.min(size.width, size.height) < spec.masterMinPx) {
          errors.push(`${spec.key}.${f.ext} is ${size.width}x${size.height}, min ${spec.masterMinPx}`);
        }
      }
    }
    const lane = liveLane(spec.key, spec.status, found);
    counts[lane] += 1;
    const present = found.map((f) => f.ext).join(",") || "—";
    lines.push(`- \`${spec.key}\` ${lane} (${present})`);
  }
  lines.push(
    "",
    "```",
    `${band} REQUIRED ${counts.REQUIRED}`,
    `${band} PRODUCTION ${counts.PRODUCTION}`,
    `${band} PLACEHOLDER ${counts.PLACEHOLDER}`,
    `${band} MISSING ${counts.MISSING}`,
    "```",
    ""
  );
}

const contracted = new Set(T1_ASSET_CONTRACT.map((s) => s.key));
const extras: string[] = [];
for (const abs of walkFiles(t1Root)) {
  const rel = path.relative(t1Root, abs).replace(/\\/g, "/");
  if (/\.(ts|md)$/i.test(rel)) continue;
  const m = rel.match(/^(.*)\.(webp|png|svg)$/i);
  if (!m) continue;
  if (!contracted.has(m[1])) extras.push(rel);
}
if (extras.length) {
  warnings.push(`uncontracted files: ${extras.join(", ")}`);
}

lines.push("## Notes", "");
lines.push("- Alpha channel is **manual QA** (no fragile decoder).");
lines.push("- SVG-only keys count as PLACEHOLDER even if the drawing is pretty.");
lines.push("- Generated `PRODUCTION` means a WebP/PNG that meets master min px is **on disk** (`PRODUCTION_PRESENT`).");
lines.push("- `PRODUCTION_ACCEPTED` is visual QA only. It is appended from `docs/art/T1_ASSET_VISUAL_ACCEPTANCE.md` and is not a contract.ts status.");
lines.push("");

const visualPath = path.join(repoRoot, "docs", "art", "T1_ASSET_VISUAL_ACCEPTANCE.md");
if (existsSync(visualPath)) {
  lines.push(readFileSync(visualPath, "utf8").trim(), "");
}

if (warnings.length) {
  lines.push("## Warnings", "");
  for (const w of warnings) lines.push(`- ${w}`);
  lines.push("");
}

writeFileSync(statusPath, `${lines.join("\n")}\n`);

for (const w of warnings) console.warn(`warn: ${w}`);
for (const e of errors) console.error(`error: ${e}`);
console.log(`wrote ${path.relative(repoRoot, statusPath)}`);

if (errors.length) {
  process.exitCode = 1;
}
