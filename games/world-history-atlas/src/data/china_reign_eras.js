  function getChineseEraInfo(rawYear) {
    const year = skipZeroYear(rawYear, 1);
    if (year < -841) {
      return getPreGongheEraInfo(year);
    }
    const gz = getGanZhi(year);

    // Binary search over sorted REIGN_ERAS
    let lo = 0;
    let hi = REIGN_ERAS.length - 1;
    let matched = REIGN_ERAS[hi];
    while (lo <= hi) {
      const mid = (lo + hi) >> 1;
      const row = REIGN_ERAS[mid];
      if (year < row[0]) {
        hi = mid - 1;
      } else if (year > row[1]) {
        lo = mid + 1;
      } else {
        matched = row;
        break;
      }
    }

    const [startY, , dynasty, monarch, eraPrefix, startNum, parallel] = matched;
    const offset = yearToOrdinal(year) - yearToOrdinal(startY);
    const yrNum = startNum + offset;
    const cnNum = toChineseOrdinal(yrNum);

    let reignLabel;
    if (year >= 1949) {
      reignLabel = yrNum === 1 ? "中华人民共和国开国元年" : `中华人民共和国成立第${yrNum}年`;
    } else if (dynasty === "中华民国") {
      reignLabel = `中华民国${cnNum}年`;
    } else if (eraPrefix === "共和") {
      reignLabel = `西周共和${cnNum}年`;
    } else if (eraPrefix) {
      reignLabel = `${monarch}${eraPrefix}${cnNum}年`;
    } else {
      reignLabel = `${monarch}${cnNum}年`;
    }

    return {
      year,
      ganzhi: gz,
      isPreGonghe: false,
      dynasty,
      monarch,
      eraName: eraPrefix || "",
      regnalYearNum: yrNum,
      reignLabel,
      shortReignLabel: reignLabel,
      parallel: parallel || "",
      fullLabel: `${gz} · ${dynasty} · ${reignLabel}`
    };
  }

  function formatYearCompact(rawYear) {
    const y = skipZeroYear(rawYear, 1);
    return y < 0 ? `前${Math.abs(y)}年` : `公元${y}年`;
  }

