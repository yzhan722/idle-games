// Build src/data/capitals.js from the researched tools/capitals/capitals.json
//   { polity: [[fromYear, toYearExclusive, name, lon, lat], ...] }  ->  { polity: [[from, to, name, x, y], ...] }
// Usage (atlas root): node tools/capitals/build.mjs   (needs tools/units/node_modules for d3-geo)
// With --merge it first merges tools/capitals/out/capitals_*.json (the research chunks) into capitals.json.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ATLAS = path.join(HERE, "..", "..");
const require = createRequire(path.join(ATLAS, "tools/units/package.json"));
const { geoNaturalEarth1 } = await import(pathToFileURL(require.resolve("d3-geo")).href);

const sandbox = { HistoryAtlas: {} };
for (const f of ["src/data/empires_db.js", "src/data/map_units.js"]) new Function("window", fs.readFileSync(path.join(ATLAS, f), "utf8"))(sandbox);
const H = sandbox.HistoryAtlas;
const P = H.MAP_UNITS.proj;
const proj = geoNaturalEarth1().rotate([P.rotate, 0]).scale(P.scale).translate([P.tx, P.ty]).precision(0);

const srcPath = path.join(HERE, "capitals.json");
if (process.argv.includes("--merge")) {
  const merged = {};
  const outDir = path.join(HERE, "out");
  for (const f of fs.readdirSync(outDir).filter(f => /^capitals_\d+\.json$/.test(f)).sort()) {
    Object.assign(merged, JSON.parse(fs.readFileSync(path.join(outDir, f), "utf8")));
  }
  fs.writeFileSync(srcPath, JSON.stringify(merged, null, 1) + "\n", "utf8");
}

const parseYear = s => (s.trim() === "至今" ? 2027 : s.trim().startsWith("前") ? -Number(s.trim().slice(1)) : Number(s.trim()));
const span = name => {
  const m = String((H.EMPIRES[name] || {}).era_span || "").split(" - ");
  return m.length === 2 ? [parseYear(m[0]), parseYear(m[1])] : null;
};

const data = JSON.parse(fs.readFileSync(srcPath, "utf8"));
const out = {}, problems = [];
let rows = 0;
for (const [name, list] of Object.entries(data)) {
  if (!H.EMPIRES[name]) { problems.push(`${name}: not in empires_db`); continue; }
  const sp = span(name);
  let last = -Infinity;
  const res = [];
  for (const r of list) {
    const [a, b, cap, lon, lat] = r;
    const bad = m => problems.push(`${name} ${a}-${b} ${cap}: ${m}`);
    if (!Number.isInteger(a) || !Number.isInteger(b) || a >= b || a === 0) { bad("bad years"); continue; }
    if (a < last) { bad("overlaps the previous row"); continue; }
    if (sp && (a < sp[0] - 10 || b > sp[1] + 16)) bad(`outside era_span ${sp.join("..")}`);
    if (!(Math.abs(lon) <= 180 && Math.abs(lat) <= 85) || !cap) { bad("bad place"); continue; }
    last = b;
    const [x, y] = proj([lon, lat]);
    res.push([a, b, cap, Math.round(x * 10) / 10, Math.round(y * 10) / 10]);
  }
  if (res.length) { out[name] = res; rows += res.length; }
}
fs.writeFileSync(path.join(ATLAS, "src/data/capitals.js"),
  `// Generated by tools/capitals/build.mjs from tools/capitals/capitals.json — capital of each state over time\n// [fromYear, toYearExclusive, name, x, y] in map coordinates\nwindow.HistoryAtlas = window.HistoryAtlas || {};\nwindow.HistoryAtlas.CAPITALS = ${JSON.stringify(out)};\n`, "utf8");
console.log("polities", Object.keys(out).length, "rows", rows);
if (problems.length) { console.log(problems.slice(0, 60).join("\n")); if (problems.length > 60) console.log(`(+${problems.length - 60})`); }
