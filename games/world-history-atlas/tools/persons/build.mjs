// Build the person view data from tools/persons/data/*.json
//   src/data/persons_index.js   small index loaded with the page
//   src/data/persons/<id>.js    one file per person, loaded on demand (stops projected to map x/y)
// Usage (atlas root): node tools/persons/build.mjs   (needs tools/units/node_modules for d3-geo)
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createRequire } from "node:module";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ATLAS = path.join(HERE, "..", "..");
const require = createRequire(path.join(ATLAS, "tools/units/package.json"));
const { geoNaturalEarth1 } = await import(pathToFileURL(require.resolve("d3-geo")).href);

const sandbox = { HistoryAtlas: {} };
for (const f of ["src/data/empires_db.js", "src/data/map_units.js"]) new Function("window", fs.readFileSync(path.join(ATLAS, f), "utf8"))(sandbox);
const H = sandbox.HistoryAtlas;
const P = H.MAP_UNITS.proj;
const proj = geoNaturalEarth1().rotate([P.rotate, 0]).scale(P.scale).translate([P.tx, P.ty]).precision(0);

const KINDS = new Set(["出生", "求学", "任职", "执政", "出使", "征战", "航行", "旅行", "传教", "流亡", "贬谪", "著述", "去世", "其他"]);
const CONF = new Set(["史料确证", "学界推测", "传说"]);
const dataDir = path.join(HERE, "data");
const outDir = path.join(ATLAS, "src/data/persons");
fs.mkdirSync(outDir, { recursive: true });

const index = [], problems = [];
const ids = new Set();
for (const f of fs.readdirSync(dataDir).filter(f => f.endsWith(".json")).sort()) {
  let p;
  try { p = JSON.parse(fs.readFileSync(path.join(dataDir, f), "utf8")); } catch (e) { problems.push(`${f}: bad JSON`); continue; }
  const bad = m => problems.push(`${p.id || f}: ${m}`);
  if (!/^[a-z0-9-]+$/.test(p.id || "")) bad("bad id");
  if (ids.has(p.id)) bad("duplicate id"); ids.add(p.id);
  if (!["中国", "世界"].includes(p.group)) bad(`bad group ${p.group}`);
  if (!Number.isInteger(p.born) || !Number.isInteger(p.died) || p.born >= p.died || p.born === 0 || p.died === 0) bad(`bad life ${p.born}-${p.died}`);
  if (p.died > 1949 && p.group) { /* allowed: life may end after 1949 only if nothing after 1949 is shown */ }
  if (p.polity && !H.EMPIRES[p.polity]) bad(`unknown polity ${p.polity}`);
  if (!CONF.has(p.confidence)) bad(`bad confidence ${p.confidence}`);
  const stops = Array.isArray(p.stops) ? p.stops : [];
  if (stops.length < 3) bad(`only ${stops.length} stops`);
  let last = -Infinity;
  const out = [];
  for (const s of stops) {
    if (!Number.isInteger(s.year) || s.year === 0) { bad(`stop year ${s.year}`); continue; }
    const to = Number.isInteger(s.to) ? s.to : s.year;
    if (s.year < last) bad(`stops not sorted at ${s.year}`);
    last = s.year;
    if (s.year < p.born - 1 || to > p.died + 1) bad(`stop ${s.year}-${to} outside life`);
    if (to > 1949) bad(`stop after 1949 (${to})`);
    if (!(Math.abs(s.lon) <= 180 && Math.abs(s.lat) <= 90)) { bad(`stop ${s.year} bad coords`); continue; }
    if (!KINDS.has(s.kind)) bad(`stop ${s.year} bad kind ${s.kind}`);
    if (!CONF.has(s.confidence)) bad(`stop ${s.year} bad confidence`);
    if (!s.place || !s.event || !s.source) bad(`stop ${s.year} missing place/event/source`);
    // the map is drawn from 58S to 84N (no Antarctica): polar stops are pinned to the map edge, the text keeps the real place
    const [x, y] = proj([s.lon, Math.max(-58, Math.min(83.5, s.lat))]);
    out.push({ year: s.year, to, x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10, place: s.place, event: s.event, kind: s.kind, confidence: s.confidence, source: s.source });
  }
  const rec = { id: p.id, name: p.name, name_alt: p.name_alt || "", group: p.group, born: p.born, died: p.died,
    born_approx: !!p.born_approx, died_approx: !!p.died_approx, role: p.role, polity: p.polity || "",
    summary: p.summary, confidence: p.confidence, sources: p.sources, stops: out };
  fs.writeFileSync(path.join(outDir, `${p.id}.js`),
    `// Generated by tools/persons/build.mjs from tools/persons/data/${f}\nwindow.HistoryAtlas = window.HistoryAtlas || {};\n(window.HistoryAtlas.PERSONS = window.HistoryAtlas.PERSONS || {})[${JSON.stringify(p.id)}] = ${JSON.stringify(rec)};\n`, "utf8");
  index.push({ id: p.id, name: p.name, group: p.group, born: p.born, died: p.died, role: p.role, polity: p.polity || "", n: out.length });
}
index.sort((a, b) => a.born - b.born);
fs.writeFileSync(path.join(ATLAS, "src/data/persons_index.js"),
  `// Generated by tools/persons/build.mjs — person view index (full records load on demand from src/data/persons/)\nwindow.HistoryAtlas = window.HistoryAtlas || {};\nwindow.HistoryAtlas.PERSONS_INDEX = ${JSON.stringify(index)};\n`, "utf8");
// drop generated files whose source was removed
for (const f of fs.readdirSync(outDir)) if (f.endsWith(".js") && !ids.has(f.slice(0, -3))) fs.unlinkSync(path.join(outDir, f));
console.log("persons", index.length, "stops", index.reduce((a, p) => a + p.n, 0));
if (problems.length) { console.log(problems.join("\n")); process.exitCode = 1; }
